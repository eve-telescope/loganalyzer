/** The panels' numbers, the table sizes with their first rows, and the
 * link preview text. */
function panels(fixture: string, filters: Partial<Filters>) {
  const merged = { ...NO_FILTERS, ...filters };
  const result = analyze(events(fixture), merged);
  return plain({
    summary: result.summary,
    details: result.details,
    peakDps: result.peakDps,
    tankSupportRatio: result.tankSupportRatio,
    neutPressureIn: result.neutPressureIn,
    neutPressureOut: result.neutPressureOut,
    selection: result.selection,
    hiddenSeries: result.hiddenSeries,
    selectionLabel: result.selectionLabel,
    engagement: result.engagement,
    counts: {
      timeline: result.dpsOverTime.length,
      filtered: result.filteredEvents.length,
      outgoing: result.outgoingTableRows.length,
      incoming: result.incomingTableRows.length,
      logistics: result.logiTableRows.length,
      engagementLog: result.engagementLog.length,
    },
    firstRows: {
      outgoing: result.outgoingTableRows[0] ?? null,
      incoming: result.incomingTableRows[0] ?? null,
      logistics: result.logiTableRows[0] ?? null,
      engagementLog: result.engagementLog[0] ?? null,
    },
    ogDescription: ogDescription(result.summary),
  });
}

