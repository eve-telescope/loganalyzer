/** The events the parser makes of a fixture log. */
function events(fixture: string): CombatEventData[] {
  const path = new URL(`../../../tests/fixtures/parser/${fixture}.expected.json`, import.meta.url);
  return (JSON.parse(readFileSync(path, 'utf8')) as { events: CombatEventData[] }).events;
}

/** Sets as arrays, so the results compare as JSON. */
function plain(value: unknown): unknown {
  return JSON.parse(JSON.stringify(value, (_, v) => (v instanceof Set ? [...v] : v)));
}

