-- The analyzer's schema: uploaded logs, their events, and the EVE names
-- resolved through ESI.

-- Case- and accent-insensitive comparison for EVE names, as the MySQL
-- utf8mb4_unicode_ci collation compared them: lookups and the unique key
-- of eve_entities treat "aria vex" and "Aria Vex" as one name.
create collation ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

create table combat_logs (
    id bigint generated by default as identity primary key,
    uuid uuid not null unique,
    listener text not null,
    -- The log's own session start, `YYYY.MM.DD HH:MM:SS`, or '' when the
    -- header has none.
    session_started text not null,
    original_filename text,
    created_at timestamptz,
    updated_at timestamptz
);

create table combat_events (
    id bigint generated by default as identity primary key,
    combat_log_id bigint not null references combat_logs on delete cascade,
    -- The log's own time, `YYYY.MM.DD HH:MM:SS`.
    timestamp text not null,
    damage bigint not null check (damage >= 0),
    direction text not null check (direction in ('outgoing', 'incoming')),
    player_name text not null,
    corporation text,
    ship_name text,
    weapon text not null,
    quality text not null,
    type text not null default 'damage' check (type in ('damage', 'logistics', 'neutralization'))
);

-- A log's events are always read in insertion order.
create index combat_events_combat_log_id_id_index on combat_events (combat_log_id, id);

create table eve_entities (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('character', 'inventory_type')),
    name text collate ci not null,
    -- Null when ESI does not know the name (cached as a miss).
    eve_id bigint,
    created_at timestamptz,
    updated_at timestamptz,
    unique (kind, name)
);
